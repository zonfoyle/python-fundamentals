"""
Day 28 – Application Programming Interfaces (API)

An API allows different applications to communicate with each other.

In web development, APIs usually communicate using HTTP
and exchange data in JSON format.
"""

# What is an API?
"""
API = Application Programming Interface

APIs allow:
- Frontend apps to talk to backend servers
- Services to communicate with other services
- Automation and integrations
"""

# REST APIs
"""
REST APIs use HTTP methods to perform CRUD operations:

GET    -> Read data
POST   -> Create data
PUT    -> Update data
DELETE -> Delete data
"""

# HTTP Request / Response Cycle
"""
Client (browser or app) sends a request
Server processes the request
Server sends a response back
"""

# Common HTTP Status Codes
"""
200 OK       -> Request successful
201 Created  -> Resource created
400 Bad Req  -> Client error
401 Unauthorized
404 Not Found
500 Server Error
"""

# Why APIs matter for Cloud / Solutions Architect roles
"""
Cloud engineers work with APIs daily:
- AWS services are API-driven
- Microservices communicate via APIs
- Infrastructure automation uses APIs
- Monitoring, logging, billing all use APIs
"""
